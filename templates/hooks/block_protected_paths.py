"""
PreToolUse hook: hard-block Edit/Write to paths the house rules protect. Turns a CLAUDE.md
"never hand-edit X" rule from prose into a machine gate.

Contract: reads the hook JSON on stdin; exit 2 blocks the tool call with the stderr message shown
to the agent; exit 0 allows. Never blocks reads. Malformed input never bricks the harness.
Register in .claude/settings.json with an absolute $CLAUDE_PROJECT_DIR path: a relative path breaks
the moment the shell's working directory moves.

Fill PROTECTED with this repo's paths (lower-case, forward slashes, relative to the repo root; a
folder entry ends in "/" and matches at a folder boundary, so "data/" catches data/x.csv and
src/data/x.csv but never AppData/; a file entry such as "docs/index.md" matches that exact path) and
PROTECTED_SUFFIXES with file kinds only a tool should write. Typical entries: vendor folders,
generated files (an index, a catalog, a view), a read-only synced copy, binary payloads.

Optional, the data home: when CLAUDE.md's data ground rule keeps local data in a machine-level
folder outside the repo (data only, one folder per project, named by an env var), fill all three:
DATA_HOME_ENV, DATA_HOME_DEFAULT (the real home, since the variable may be set only in a .env this
hook never reads) and DATA_PROJECT (always: a worktree or a renamed clone sits in a folder with
another name). Inside the data home an edit outside this project's folder is blocked (another
project's data, or the data home's own files), and so is an edit under DATA_PROTECTED (relative to
this project's folder, same spelling as PROTECTED: append-only inputs, generated outputs). The
home's paths are resolved (.., symlinks, junctions) before they are compared. Leave DATA_HOME_ENV
and DATA_HOME_DEFAULT empty when the repo keeps its data in data/; the section is then off.
"""
import json
import os
import re
import sys

PROTECTED = (
    # ("vendor/",            "vendor folder (import-only; CLAUDE.md rule N)"),
    # ("docs/generated/",    "generated; rebuild with `uv run scripts/build.py`"),
)
PROTECTED_SUFFIXES = (
    # (".lock",              "lock files are written by the package manager"),
)

DATA_HOME_ENV = ""        # the env var that names the data home, e.g. "DATA_ROOT"
DATA_HOME_DEFAULT = ""    # the data home when that variable is unset, e.g. "~/.data"
DATA_PROJECT = ""         # this project's folder in the data home, e.g. the repo's name
DATA_PROTECTED = (
    # ("raw/",               "append-only inputs: the pipeline adds files, nothing edits them"),
    # ("reports/",           "generated by the pipeline; rebuild it, never hand-edit"),
)


def norm(path: str) -> str:
    return path.replace("\\", "/").lower().rstrip("/")


def resolved(path: str) -> str:
    # .. segments, symlinks and junctions resolved; works for a file that does not exist yet.
    return norm(os.path.realpath(os.path.expanduser(path)))


def block(raw: str, why: str) -> int:
    print(f"BLOCKED by .claude/hooks/block_protected_paths.py: '{raw}' is protected ({why}). "
          f"If this edit is genuinely required, the owner lifts the block explicitly.", file=sys.stderr)
    return 2


def data_home_reason(raw: str, root: str) -> str | None:
    # The data home sits outside the repo, so it is matched on the resolved absolute path, before
    # the outside-the-repo rule below lets everything else through.
    home = (os.environ.get(DATA_HOME_ENV) if DATA_HOME_ENV else None) or DATA_HOME_DEFAULT
    if not home or not raw:
        return None
    home, p = resolved(home), resolved(raw)
    if not p.startswith(home + "/"):
        return None
    rel = p[len(home) + 1:]
    project = norm(DATA_PROJECT) or root.rsplit("/", 1)[-1]
    if rel != project and not rel.startswith(project + "/"):
        return f"outside this project's folder '{project}/' in the data home: another project's data, or the data home's own files"
    sub = rel[len(project) + 1:]
    for frag, why in DATA_PROTECTED:
        frag = frag.replace("\\", "/").lower()
        if (sub.startswith(frag) if frag.endswith("/") else sub == frag):
            return why
    return None


def main() -> int:
    try:
        payload = json.load(sys.stdin)
    except Exception:
        return 0
    if payload.get("tool_name") not in ("Edit", "Write", "MultiEdit", "NotebookEdit"):
        return 0
    tool_input = payload.get("tool_input") or {}
    raw = tool_input.get("file_path") or tool_input.get("notebook_path") or ""
    p = norm(raw)
    # Match inside the repo, not the machine: a path under the project dir is compared relative to
    # it, anchored at a folder boundary, so protecting "data/" never catches "AppData/Local/...".
    root = norm(os.environ.get("CLAUDE_PROJECT_DIR") or payload.get("cwd") or os.getcwd())
    why = data_home_reason(raw, root)
    if why:
        return block(raw, why)
    if root and p.startswith(root + "/"):
        p = p[len(root) + 1:]
    elif p.startswith("/") or re.match(r"^[a-z]:/", p):
        return 0  # an absolute path outside this repo and its data home: its house rules don't apply there
    for frag, why in PROTECTED:
        hit = (p.startswith(frag) or f"/{frag}" in p) if frag.endswith("/") else p == frag
        if hit:
            return block(raw, why)
    for suf, why in PROTECTED_SUFFIXES:
        if p.endswith(suf):
            return block(raw, why)
    return 0


if __name__ == "__main__":
    sys.exit(main())
